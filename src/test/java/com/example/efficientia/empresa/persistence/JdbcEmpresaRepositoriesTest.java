package com.example.efficientia.empresa.persistence;

import com.example.efficientia.empresa.domain.Empresa;
import com.example.efficientia.empresa.domain.EmpresaAdmin;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.time.Instant;

import static org.assertj.core.api.Assertions.assertThat;

class JdbcEmpresaRepositoriesTest {

    @Test
    void empresaExistenteNoBancoPodeReceberAdminEPersistirLogin() {
        DriverManagerDataSource dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:empresa_login;DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE public.empresa (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, endereco_id INTEGER, codigo_interno VARCHAR(20), nome VARCHAR(150), nome_fantasia VARCHAR(150), razao_social VARCHAR(150), cnpj VARCHAR(14), email VARCHAR(150), telefone VARCHAR(20), logo_url VARCHAR(500), etapa_cadastro INTEGER, cadastro_completo BOOLEAN, senha_hash VARCHAR(255), ativo BOOLEAN, criado_em TIMESTAMP, atualizado_em TIMESTAMP)");
        jdbc.execute("CREATE TABLE public.empresa_admin (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, empresa_id BIGINT, codigo_empresa VARCHAR(20), cnpj_empresa VARCHAR(14), nome VARCHAR(150), email VARCHAR(150), cpf VARCHAR(11), telefone VARCHAR(20), cargo VARCHAR(100), senha_hash VARCHAR(255), ativo BOOLEAN, criado_em TIMESTAMP, atualizado_em TIMESTAMP)");

        InMemoryEmpresaRepository empresas = new InMemoryEmpresaRepository();
        InMemoryEmpresaAdminRepository admins = new InMemoryEmpresaAdminRepository();
        empresas.usarBancoQuandoDisponivel(jdbc);
        admins.usarBancoQuandoDisponivel(jdbc);
        Instant agora = Instant.now();
        Empresa empresa = new Empresa(null, null, "EMP-TESTE", "Empresa de teste", "Empresa de teste", "Empresa de teste", "91791993667077", "empresa@example.com", null, null, 1, false, null, true, agora, agora);
        empresas.salvar(empresa);

        assertThat(empresas.buscarPorCnpj("91791993667077")).isPresent();
        assertThat(empresas.buscarPorId(empresa.getId())).isPresent();
        assertThat(admins.contarPorEmpresaId(empresa.getId())).isZero();

        EmpresaAdmin admin = new EmpresaAdmin(null, empresa.getId(), empresa.getCodigoEmpresa(), empresa.getCnpj(), "Admin Teste", "admin@example.com", null, null, "Administrador", "hash", true, agora, agora);
        admins.salvar(admin);

        assertThat(admin.getId()).isNotNull();
        assertThat(admins.contarPorEmpresaId(empresa.getId())).isEqualTo(1);
        assertThat(admins.buscarPorEmail("ADMIN@EXAMPLE.COM")).isPresent();
        assertThat(admins.listarPorEmpresaId(empresa.getId())).extracting(EmpresaAdmin::getNome).containsExactly("Admin Teste");

        admin.setNome("Admin Atualizado");
        admins.salvar(admin);
        assertThat(admins.buscarPorId(admin.getId())).get().extracting(EmpresaAdmin::getNome).isEqualTo("Admin Atualizado");
    }
}
